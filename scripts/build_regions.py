#!/usr/bin/env python3
"""Build static ES/EN/BR regional editions from the shared page templates."""
import html
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGES = ('index.html', 'familias.html', 'portfolio.html', 'hat-usb3.html')
LANGUAGES = {'es': 'es', 'en': 'en', 'br': 'pt'}
SPAN_ES = re.compile(r'<span class="lang lang-es">(.*?)</span>', re.S)


def main():
    subprocess.run([sys.executable, str(ROOT/'scripts/build_families.py')], check=True)
    translations = json.loads((ROOT/'data/pt-BR.json').read_text())
    config = json.loads((ROOT/'data/markets.json').read_text())
    config['countries'] = json.loads((ROOT/'data/countries.json').read_text())
    source = {name: (ROOT/name).read_text() for name in PAGES}
    missing = sorted({html.unescape(s) for content in source.values() for s in SPAN_ES.findall(content)} - translations.keys())
    if missing:
        print(json.dumps({'missing_portuguese': missing}, ensure_ascii=False, indent=2))
        raise SystemExit('Complete data/pt-BR.json before generating regional editions.')
    public_config = {key: config[key] for key in ['version', 'default', 'country_market', 'markets', 'countries']}
    (ROOT/'regional-data.js').write_text('/* Generated by scripts/build_regions.py. */\nwindow.MRF_REGIONS = ' + json.dumps(public_config, ensure_ascii=False, separators=(',', ':')) + ';\n')

    def translate_span(match):
        translated = translations[html.unescape(match[1])]
        escaped = html.escape(translated).replace('&lt;br&gt;', '<br>').replace('&lt;br/&gt;', '<br>')
        return match[0] + '<span class="lang lang-pt">' + escaped + '</span>'

    for name, content in source.items():
        content = re.sub(r'<span class="lang lang-pt">.*?</span>', '', content, flags=re.S)
        content = SPAN_ES.sub(translate_span, content)
        if '<base ' not in content:
            content = content.replace('<head>', '<head><base href="/">', 1)
        content = re.sub(r'(src|href)="(site\.js|studio\.js|country\.js|regional-data\.js|prototype\.css)(?:\?[^" ]*)?"', r'\1="\2?v=15"', content)
        if 'regional-data.js' not in content:
            content = content.replace('<script src="site.js?v=15"', '<script src="regional-data.js?v=15" defer></script><script src="site.js?v=15"', 1)
        if 'data-set-lang="pt"' not in content:
            content = re.sub(r'(<button[^>]*data-set-lang="en"[^>]*>.*?</button>)', r'\1<span aria-hidden="true">/</span><button type="button" data-set-lang="pt" aria-pressed="false" lang="pt-BR" aria-label="Português">BR</button>', content, count=1)
        content = re.sub(r' data-name-pt="[^"]*"', '', content)
        content = re.sub(r'data-name-es="([^"]*)"', lambda m: m[0] + ' data-name-pt="' + html.escape(translations.get(html.unescape(m[1]), html.unescape(m[1])), quote=True) + '"', content)
        content = re.sub(r' data-alt-pt="[^"]*"', '', content)
        content = re.sub(r'data-alt-es="([^"]*)"', lambda m: m[0] + ' data-alt-pt="' + html.escape(translations.get(html.unescape(m[1]), html.unescape(m[1])), quote=True) + '"', content)
        title_pt = {'index.html': 'Marsupial RF — Eletrônica, antenas e sistemas RF', 'familias.html': 'Marsupial RF — Produtos e serviços', 'portfolio.html': 'Marsupial RF — Portfolio', 'hat-usb3.html': 'Marsupial RF — Dual-controller True 2xUSB-3 Xpansion HAT para Raspberry Pi 5'}[name]
        content = re.sub(r' data-title-pt="[^"]*"', '', content)
        content = content.replace('<body ', '<body data-title-pt="' + title_pt + '" ', 1)
        (ROOT/name).write_text(content)
        for prefix, lang in LANGUAGES.items():
            for market in config['markets']:
                folder = ROOT/prefix/market['id']
                folder.mkdir(parents=True, exist_ok=True)
                page = re.sub(r'<html lang="[^"]*"', '<html lang="' + ('pt-BR' if lang == 'pt' else lang) + '"', content, count=1)
                page = re.sub(r'data-lang="[^"]*"', 'data-lang="' + lang + '"', page, count=1)
                for kind, ids in market['featured'].items():
                    page = page.replace('id="' + kind + '" data-carousel', 'id="' + kind + '" data-featured-ids="' + ','.join(ids) + '" data-carousel')
                (folder/name).write_text(page)
    print(json.dumps({'regional_pages': len(PAGES)*len(LANGUAGES)*len(config['markets']), 'countries': len(config['countries']), 'languages': list(LANGUAGES)}))


if __name__ == '__main__':
    main()
